-- 다시 만나: Supabase 스키마 및 테이블.
-- 실행 위치: Supabase SQL Editor. 기존 테이블이 있으면 열·기본키 호환성을 확인한다.
-- 실행 후 Data API 설정의 Exposed schemas 에 aio-03-p2-team1-demo 를 추가한다(PGRST106 방지).

create schema if not exists "aio-03-p2-team1-demo";

create table if not exists "aio-03-p2-team1-demo".documents (
    owner      text        not null,
    kind       text        not null check (kind in ('identity','thread','memory','saved','run','subscription','notification','post','comment')),
    id         text        not null,
    data       jsonb       not null,
    updated_at timestamptz not null default now(),
    primary key (owner, kind, id)
);

create index if not exists documents_owner_kind_updated
    on "aio-03-p2-team1-demo".documents (owner, kind, updated_at desc);

-- RLS 를 켜고 공개 정책은 만들지 않는다. service_role 만 접근한다(브라우저는 FastAPI 를 거친다).
alter table "aio-03-p2-team1-demo".documents enable row level security;

revoke all on schema "aio-03-p2-team1-demo" from anon, authenticated;
revoke all on all tables in schema "aio-03-p2-team1-demo" from anon, authenticated;

grant usage on schema "aio-03-p2-team1-demo" to service_role;
grant select, insert, update, delete on "aio-03-p2-team1-demo".documents to service_role;

-- 게시글 음성은 서버만 읽고 쓰는 private Storage bucket 에 둔다.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('post-audio', 'post-audio', false, 10485760, array['audio/mpeg','audio/mp4','audio/wav','audio/ogg'])
on conflict (id) do update set
    public = excluded.public,
    file_size_limit = excluded.file_size_limit,
    allowed_mime_types = excluded.allowed_mime_types;

-- 품종 기준정보. init_kinds_supabase.py 가 반복 동기화하며 사라진 코드는 비활성 보존한다.
create table if not exists "aio-03-p2-team1-demo".kinds (
    id bigint generated by default as identity primary key,
    species text not null check (species in ('dog','cat','other')),
    kind_code text not null unique,
    name text not null,
    search_name text not null,
    active boolean not null default true,
    source text not null default 'animal_api',
    source_updated_at timestamptz,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);
create index if not exists kinds_search_name_idx on "aio-03-p2-team1-demo".kinds(species, search_name);
create index if not exists kinds_name_idx on "aio-03-p2-team1-demo".kinds(species, lower(name));

create table if not exists "aio-03-p2-team1-demo".kind_aliases (
    id bigint generated by default as identity primary key,
    kind_code text not null references "aio-03-p2-team1-demo".kinds(kind_code) on update cascade on delete cascade,
    alias text not null,
    search_alias text not null,
    source text not null default 'curated',
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    unique(kind_code, search_alias)
);
create index if not exists kind_aliases_search_idx on "aio-03-p2-team1-demo".kind_aliases(search_alias);
create index if not exists kind_aliases_code_idx on "aio-03-p2-team1-demo".kind_aliases(kind_code);
alter table "aio-03-p2-team1-demo".kinds enable row level security;
alter table "aio-03-p2-team1-demo".kind_aliases enable row level security;
revoke all on "aio-03-p2-team1-demo".kinds, "aio-03-p2-team1-demo".kind_aliases from anon, authenticated;
grant select, insert, update, delete on "aio-03-p2-team1-demo".kinds, "aio-03-p2-team1-demo".kind_aliases to service_role;
grant usage, select on all sequences in schema "aio-03-p2-team1-demo" to service_role;

